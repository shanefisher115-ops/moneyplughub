$BLOCK_LOOPS = @'
# REGION: LOOPS
$script:LOOP_REGISTRY = [ordered]@{}

function Start-PrimordialLoop {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$Name,
        [int]$IntervalSeconds = 5,
        [scriptblock]$Action = { },
        [int]$MaxCycles = 0
    )
    $key = $Name.ToLower()
    if ($script:LOOP_REGISTRY.Contains($key)) {
        Write-Host " [LOOP] '$Name' already running." -ForegroundColor Yellow; return
    }

    $actStr = $Action.ToString()
    $job = Start-Job -Name "PrimordialLoop_$Name" -ScriptBlock {
        param($interval,$maxC,$actStr)
        $act = [scriptblock]::Create($actStr)
        $c = 0
        while ($maxC -eq 0 -or $c -lt $maxC) {
            try { & $act } catch { }
            $c++
            Start-Sleep -Seconds $interval
        }
    } -ArgumentList $IntervalSeconds,$MaxCycles,$actStr

    $loop = [PSCustomObject]@{
        Name = $Name; IntervalSeconds = $IntervalSeconds
        Action = $Action; MaxCycles = $MaxCycles
        Cycles = 0; Status = 'RUNNING'
        StartTime = Get-Date; Job = $job
    }
    $script:LOOP_REGISTRY[$key] = $loop
    Write-Host (" [LOOP] Started: {0} (every {1}s, job #{2})" -f $Name,$IntervalSeconds,$job.Id) -ForegroundColor Green
    return $loop
}

function Stop-PrimordialLoop {
    [CmdletBinding()]
    param([Parameter(Mandatory)][string]$Name)
    $key = $Name.ToLower()
    if ($script:LOOP_REGISTRY.Contains($key)) {
        $lp = $script:LOOP_REGISTRY[$key]
        if ($lp.Job) {
            Stop-Job $lp.Job -ErrorAction SilentlyContinue
            Remove-Job $lp.Job -ErrorAction SilentlyContinue
        }
        $script:LOOP_REGISTRY.Remove($key)
        Write-Host " [LOOP] Stopped: $Name" -ForegroundColor Yellow
    } else {
        Write-Host " [LOOP] Not found: $Name" -ForegroundColor Red
    }
}

function Get-PrimordialLoops {
    if ($script:LOOP_REGISTRY.Count -eq 0) {
        Write-Host " [LOOP] No active loops." -ForegroundColor Yellow; return
    }
    Write-Host "`n == ACTIVE LOOPS ==" -ForegroundColor Cyan
    $script:LOOP_REGISTRY.GetEnumerator() | ForEach-Object {
        $lp = $_.Value
        Write-Host (" [{0}] {1,-15} | every {2}s | job:{3}" -f
            $lp.Status,$lp.Name,$lp.IntervalSeconds,$lp.Job.Id) -ForegroundColor White
    }
    Write-Host ""
}

function Stop-AllPrimordialLoops {
    [CmdletBinding()]
    param()
    $keys = @($script:LOOP_REGISTRY.Keys)
    foreach ($k in $keys) { Stop-PrimordialLoop -Name $k }
    Write-Host " [LOOP] All loops stopped." -ForegroundColor Yellow
}

Set-Alias -Name loops -Value Get-PrimordialLoops -Scope Global -Force
'@

