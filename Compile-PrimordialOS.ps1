function Get-CleanHeader {
    param([string]$FilePath)
    if (-not (Test-Path $FilePath)) { return '' }
    $lines = Get-Content $FilePath -Encoding UTF8
    $cutIndex = -1
    for ($i = 0; $i -lt $lines.Count; $i++) {
        foreach ($anchor in $STRIP_ANCHORS) {
            if ($lines[$i] -match [regex]::Escape($anchor)) {
                $cutIndex = $i; break
            }
        }
        if ($cutIndex -ge 0) { break }
    }
    if ($cutIndex -le 0) { return '' }
    return ($lines[0..($cutIndex - 1)] -join "`n")
}

function Test-ScriptSyntax {
    param([string]$FilePath)
    $errors = $null
    $tokens = $null
    [System.Management.Automation.Language.Parser]::ParseFile($FilePath, [ref]$tokens, [ref]$errors) | Out-Null
    if ($errors.Count -gt 0) {
        $errors | ForEach-Object {
            Write-Host ("Syntax: Line {0} — {1}" -f $_.Extent.StartLineNumber, $_.Message) -ForegroundColor Red
        }
        return $false
    }
    return $true
}

function Write-Manifest {
    param([string]$Path)
    if (-not (Test-Path $Path)) {
        $MANIFEST_CONTENT | Set-Content -Path $Path -Encoding UTF8 -Force
        Write-Host "Manifest written: $Path" -ForegroundColor Green
    } else {
        Write-Host "Manifest already exists — skipping" -ForegroundColor Yellow
    }
}

